export async function generateOfficeDoc(topic: string): Promise<{ title: string; html: string }> {
  const cleanTopic = topic.trim() || "Business Operations Plan";
  try {
    const token = typeof window !== "undefined" ? localStorage.getItem("token") : null;
    if (token && token.length > 10) {
      const res = await fetch("/api/v1/ai/chat", {
        method: "POST",
        headers: { "Content-Type": "application/json", Authorization: `Bearer ${token}` },
        body: JSON.stringify({
          message: `Write a concise professional business document in clean HTML (using h1, h2, p, ul, li tags only) about: ${cleanTopic}`,
        }),
      });
      if (res.ok) {
        const data = await res.json();
        const reply = data?.response || data?.reply || data?.message;
        if (typeof reply === "string" && reply.includes("<")) {
          return { title: cleanTopic, html: reply };
        }
      }
    }
  } catch {}

  return {
    title: cleanTopic,
    html: `<h1>${cleanTopic}</h1><p><strong>Prepared with BERAXIS AI Studio</strong> &nbsp;|&nbsp; ${new Date().toLocaleDateString()}</p><hr/><h2>1. Executive Overview</h2><p>This document establishes the operational framework, key deliverables, and success metrics for <strong>${cleanTopic}</strong>.</p><h2>2. Core Objectives</h2><ul><li>Streamline execution across Sales, Finance, and Operations with zero manual handoffs.</li><li>Eliminate fragmented external spreadsheets and document silos.</li><li>Track weekly progress inside unified BERAXIS KPI dashboards.</li></ul><h2>3. Action Plan &amp; Ownership</h2><table border="1" style="width:100%;border-collapse:collapse;margin-top:8px;"><tr><th style="padding:8px;text-align:left;">Phase</th><th style="padding:8px;text-align:left;">Deliverable</th><th style="padding:8px;text-align:left;">Timeline</th></tr><tr><td style="padding:8px;">Phase 1</td><td style="padding:8px;">Requirements &amp; Setup</td><td style="padding:8px;">Week 1</td></tr><tr><td style="padding:8px;">Phase 2</td><td style="padding:8px;">Team Rollout &amp; Review</td><td style="padding:8px;">Week 2</td></tr></table>`,
  };
}

