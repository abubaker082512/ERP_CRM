/**
 * Filter verified real leads by query, country, industry, and city
 */
export function filterRealLeads(
    query?: string,
    country?: string,
    industry?: string,
    city?: string,
    limit: number = 50,
    skip: number = 0
): { total: number; leads: RealVerifiedLead[] } {
    let filtered = REAL_VERIFIED_LEADS;

    if (country && country !== "All") {
        const cNorm = country.toLowerCase().trim();
        filtered = filtered.filter((l) => l.country.toLowerCase().includes(cNorm) || cNorm.includes(l.country.toLowerCase()));
    }

    if (industry && industry !== "All") {
        const iNorm = industry.toLowerCase().trim();
        filtered = filtered.filter((l) => l.industry.toLowerCase().includes(iNorm) || iNorm.includes(l.industry.toLowerCase()));
    }

    if (city && city !== "All") {
        const cityNorm = city.toLowerCase().trim();
        filtered = filtered.filter((l) => l.city.toLowerCase().includes(cityNorm));
    }

    if (query && query.trim()) {
        const qNorm = query.toLowerCase().trim();
        filtered = filtered.filter(
            (l) =>
                l.company_name.toLowerCase().includes(qNorm) ||
                l.contact_name.toLowerCase().includes(qNorm) ||
                l.city.toLowerCase().includes(qNorm) ||
                l.country.toLowerCase().includes(qNorm) ||
                l.industry.toLowerCase().includes(qNorm) ||
                l.source.toLowerCase().includes(qNorm) ||
                l.job_title.toLowerCase().includes(qNorm)
        );
    }

    const total = filtered.length;
    const leads = filtered.slice(skip, skip + limit);

    return { total, leads };
}

/**
 * Mask sensitive lead contact info for locked leads
 */
export function maskLeadContact(lead: RealVerifiedLead, isUnlocked: boolean): RealVerifiedLead {
    if (isUnlocked) {
        return { ...lead, unlocked: true };
    }

    // Obfuscate phone and email
    const parts = lead.email.split("@");
    const maskedEmail = parts[0].length > 2
        ? `${parts[0].slice(0, 2)}••••@${parts[1] || "domain.com"}`
        : `•••@${parts[1] || "domain.com"}`;

    const phoneLen = lead.phone.length;
    const maskedPhone = phoneLen > 6
        ? `${lead.phone.slice(0, 4)} •••• ${lead.phone.slice(-2)}`
        : "+•• ••• ••••";

    return {
        ...lead,
        email: maskedEmail,
        phone: maskedPhone,
        phone_formatted: maskedPhone,
        whatsapp_url: undefined,
        unlocked: false,
    };
}
