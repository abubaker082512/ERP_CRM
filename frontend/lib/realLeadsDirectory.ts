export function maskLeadContact(lead: RealVerifiedLead, isUnlocked: boolean): RealVerifiedLead {
    if (isUnlocked) {
        return { ...lead, unlocked: true };
    }

    // Mask phone e.g. +92 42 •••••••• or +1 (408) •••-••••
    const phoneParts = lead.phone.split(" ");
    const maskedPhone = phoneParts.length > 2
        ? `${phoneParts[0]} ${phoneParts[1]} ••••••••`
        : lead.phone.slice(0, 5) + " ••••••••";

    // Mask email e.g. in••••@domain.com
    const emailParts = lead.email.split("@");
    const namePart = emailParts[0];
    const maskedEmail = (namePart.length > 2 ? namePart.slice(0, 2) : namePart.slice(0, 1)) + "••••@" + (emailParts[1] || "enterprise.com");

    return {
        ...lead,
        phone: maskedPhone,
        phone_formatted: maskedPhone,
        whatsapp_url: undefined, // Conceal direct WhatsApp dial until unlocked
        email: maskedEmail,
        unlocked: false
    };
}

export function filterRealLeads(
    query?: string,
    country?: string,
    industry?: string,
    city?: string
): RealVerifiedLead[] {
    return REAL_VERIFIED_LEADS.filter(lead => {
        if (query) {
            const q = query.toLowerCase();
            const matchQuery =
                lead.company_name.toLowerCase().includes(q) ||
                lead.contact_name.toLowerCase().includes(q) ||
                lead.city.toLowerCase().includes(q) ||
                lead.country.toLowerCase().includes(q) ||
                lead.industry.toLowerCase().includes(q);
            if (!matchQuery) return false;
        }

        if (country && country !== "All" && country !== "all") {
            if (lead.country.toLowerCase() !== country.toLowerCase()) return false;
        }

        if (industry && industry !== "All" && industry !== "all") {
            if (lead.industry.toLowerCase() !== industry.toLowerCase()) return false;
        }

        if (city && city !== "All" && city !== "all") {
            if (lead.city.toLowerCase() !== city.toLowerCase()) return false;
        }

        return true;
    });
}
